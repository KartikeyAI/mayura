// Writes the catalog of every @mayurajs/* package in extensions/, grouped by area:
//   - docs/reference/integrations.md, a table per area from each package's own description, linking each package's page;
//   - the "Integrations: <area>" sections of docs/README.md (between the integrations markers), which put every
//     package page in the docs navigation.
// Every extension needs its page, docs/integrations/<folder>.md, whose frontmatter names the package and its area.
// Run it after adding an extension; --check fails when either file is out of date or a page is missing.
//   node scripts/integrations-index.mjs [--check]
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { readPage } from './docs-index.mjs';

const root = fileURLToPath(new URL('..', import.meta.url));
const target = join(root, 'docs', 'reference', 'integrations.md');
const readme = join(root, 'docs', 'README.md');
const START = '<!-- integrations:start (generated by scripts/integrations-index.mjs) -->';
const END = '<!-- integrations:end -->';

/** Each area: its key (the `area` of its pages), the package name prefixes it holds, its guide, and one line about it. */
const areas = [
  { key: 'vectors', title: 'Vector stores', prefixes: ['vector-'], guide: 'guides/rag.md', about: 'Scoped vector storage beside built-in memory and native-memory adapters.' },
  { key: 'rerankers', title: 'Rerankers', prefixes: ['reranker-'], guide: 'guides/rag.md', about: 'Bounded reranking of authorized evidence by original document index.' },
  { key: 'gateways', title: 'AI gateways', prefixes: ['gateway-'], guide: 'guides/ai-gateways.md', about: 'Registry providers for explicitly configured gateways, with bounded calls and reported-cost accounting.' },
  { key: 'providers', title: 'Model providers', prefixes: ['provider-'], guide: 'guides/model-registry.md', about: 'Models as `provider/model` in a model registry, with prices.' },
  { key: 'voice', title: 'Voice', prefixes: ['voice-'], guide: 'guides/voice.md', about: 'Speech-to-text and text-to-speech in the voice registry.' },
  { key: 'storage', title: 'Storage', prefixes: ['storage-'], guide: 'guides/storage.md', about: 'Databases for runs, workflows, memory and keys, beside the built-in SQLite and PostgreSQL.' },
  { key: 'files', title: 'Files', prefixes: ['filestorage-'], guide: 'guides/files.md', about: 'Object stores and filesystems for file stores and artifacts, beside the built-in S3.' },
  { key: 'observability', title: 'Observability', prefixes: ['observability-'], guide: 'guides/observability.md', about: 'Trace exporters for observability services, over OpenTelemetry.' },
  { key: 'sandboxes', title: 'Sandboxes', prefixes: ['sandbox-'], guide: 'guides/sandboxes.md', about: 'Hosted Linux machines for agents, beside the built-in Docker sandboxes.' },
  { key: 'browsers', title: 'Browsers', prefixes: ['browser-', 'cloudflare-quick-action'], guide: 'guides/browsers.md', about: 'Hosted browsers, browser tools and a live viewer, beside the local Chrome or Edge.' },
  { key: 'authz', title: 'Authorization policies', prefixes: ['authz-'], guide: 'guides/authorization.md', about: 'External policy decisions through the scoped core authorization and audit contracts.' },
  { key: 'auth', title: 'Sign-in providers', prefixes: ['auth-'], guide: 'guides/authentication.md', about: 'Identity provider tokens as server identities.' },
  { key: 'keys', title: 'API key services', prefixes: ['km-'], guide: 'guides/authentication.md#api-keys', about: 'Keys issued by a key service, beside the built-in key manager.' },
  { key: 'deploy', title: 'Deploy targets', prefixes: ['deploy-'], guide: 'cli/deploy.md', about: 'Platforms for `mayura deploy`, beside Docker, Compose and Kubernetes.' },
];

const packages = []; const problems = [];
for (const folder of (await readdir(join(root, 'extensions'), { withFileTypes: true })).filter(item => item.isDirectory()).map(item => item.name).sort()) {
  const manifest = JSON.parse(await readFile(join(root, 'extensions', folder, 'package.json'), 'utf8'));
  const area = areas.find(candidate => candidate.prefixes.some(prefix => folder === prefix || folder.startsWith(prefix)));
  if (!area) throw new Error(`extensions/${folder} belongs to no area: add its prefix to scripts/integrations-index.mjs.`);
  if (typeof manifest.description !== 'string' || manifest.description === '') throw new Error(`extensions/${folder} has no description.`);
  let page;
  try { page = readPage(join(root, 'docs', 'integrations', `${folder}.md`)); }
  catch { problems.push(`extensions/${folder} has no page: write docs/integrations/${folder}.md (see docs/integrations/sandbox-e2b.md).`); }
  if (page && page.package !== manifest.name) problems.push(`docs/integrations/${folder}.md: package must be "${manifest.name}".`);
  if (page && page.area !== area.key) problems.push(`docs/integrations/${folder}.md: area must be "${area.key}".`);
  packages.push({ folder, name: manifest.name, description: manifest.description, area, vendor: page?.vendor || page?.title || manifest.name });
}
if (problems.length) { console.error(problems.join('\n')); process.exit(1); }

const lines = [
  '---',
  'title: "Integration packages"',
  'description: "Every @mayurajs package: model providers, voice, storage, files, observability, sandboxes, browsers, authorization, sign-in, API keys and deploy targets."',
  '---',
  '',
  `Beside \`mayura\`, ${packages.length} optional \`@mayurajs/*\` packages connect it to other services. Each is published with every Mayura`,
  'release at the same version, takes `mayura` as a peer, and is installed only if you use it:',
  '',
  '```bash',
  'npm install mayura @mayurajs/storage-mysql',
  '```',
  '',
  'The packages read no environment variables themselves: you pass credentials in as options, and deploy targets use',
  'the platform\'s own command-line tool, signed in as you. Each package has its own page, and each area\'s guide shows',
  'how the packages fit together.',
  '',
];
for (const area of areas) {
  const members = packages.filter(item => item.area === area);
  if (members.length === 0) continue;
  lines.push(`## ${area.title}`, '', `${area.about} See [${area.title === 'Deploy targets' ? 'mayura deploy' : area.title}](../${area.guide}).`, '', '| Package | What it does |', '| --- | --- |');
  for (const item of members) lines.push(`| [\`${item.name}\`](../integrations/${item.folder}.md) | ${item.description.replaceAll('|', '\\|')} |`);
  lines.push('');
}
const page = `${lines.join('\n').trimEnd()}\n`;

// The navigation sections: one per area, its packages by vendor name.
const block = [START, ''];
for (const area of areas) {
  const members = packages.filter(item => item.area === area).sort((a, b) => a.vendor.localeCompare(b.vendor) || a.name.localeCompare(b.name));
  if (members.length === 0) continue;
  block.push(`## Integrations: ${area.title.toLowerCase()}`, '');
  for (const item of members) block.push(`- [${item.vendor}](integrations/${item.folder}.md): ${item.description.replace(/\.$/u, '')}.`);
  block.push('');
}
block.push(END);
const currentReadme = await readFile(readme, 'utf8');
const startAt = currentReadme.indexOf(START); const endAt = currentReadme.indexOf(END);
if (startAt < 0 || endAt < startAt) throw new Error(`docs/README.md needs the markers ${START} and ${END} where the integration sections go.`);
const nextReadme = `${currentReadme.slice(0, startAt)}${block.join('\n')}${currentReadme.slice(endAt + END.length)}`;

if (process.argv.includes('--check')) {
  const current = await readFile(target, 'utf8').catch(() => '');
  const stale = [current !== page && 'docs/reference/integrations.md', currentReadme !== nextReadme && 'docs/README.md'].filter(Boolean);
  if (stale.length) { console.error(`${stale.join(' and ')} out of date: run node scripts/integrations-index.mjs.`); process.exit(1); }
  console.log(`docs/reference/integrations.md and docs/README.md list all ${packages.length} packages, each with its page.`);
} else {
  await writeFile(target, page);
  await writeFile(readme, nextReadme);
  console.log(`Wrote docs/reference/integrations.md and docs/README.md: ${packages.length} packages in ${new Set(packages.map(item => item.area)).size} areas.`);
}
